#!/usr/bin/env bash
# lumen benchmark harness (protocol: CLAUDE.md "Benchmark protocol").
#
# One config = one warm-up run (discarded) + RUNS measured runs, same prompt, same
# image. Reports the median of every metric. Nothing board-specific is hardcoded:
# binaries, model, image and run parameters are environment variables.
#
#   MODE=text|image          text: llama-completion; image: llama-mtmd-cli (default: image)
#   LABEL=<name>             config name used in the output file names (default: MODE)
#   BUILD_DIR                llama.cpp build with the binaries (default: build-cuda)
#   MODEL / MMPROJ / IMAGE   GGUF model, projector, test image
#   PROMPT_TEXT / PROMPT_IMAGE  prompts for each mode
#   RUNS=5  N_PREDICT=64  CTX=4096  THREADS=4  NGL=99  IMAGE_MAX_TOKENS=256
#   EXTRA_ARGS               appended to the llama.cpp command line (e.g. "-fa off")
#   REQUIRE_MAX_CLOCKS=1     refuse to run unless the GPU is pinned at its max frequency
#
# Output: bench/runs/<date>-<label>/ with per-run logs, runs.csv and summary.txt.
#
# Definitions:
#   TTFT         = wall clock, measured by scripts/ttft_wall.py: from the CLI's "ready"
#                  log line (model loaded, warm-up done) to the first generated byte on
#                  stdout. Includes image loading (JPEG decode), preprocessing, vision
#                  encoding and prefill. Model load is reported separately.
#   image encode = "mtmd batch encoding done in X ms" (vision encoder only)
#   prefill      = LLM prompt processing. libllama's "prompt eval time" runs from the
#                  first prompt llama_decode to the next synchronize(). In MODE=image the
#                  vision encoding happens inside that window (text chunk, encode, image
#                  chunk, text chunk), so prefill ms = prompt eval time - image encode.
#                  prefill t/s = prompt tokens (incl. image tokens) / prefill ms
#   decode t/s   = (eval runs) / "eval time"
#   (Before 2026-10-18 TTFT was computed as encode + prompt eval + one decode step,
#   which counted the encode twice; results.md records the correction.)
#   RAM peak     = max tegrastats "RAM used" during the run, and its delta vs the
#                  first tegrastats sample (taken 1 s before the program starts)
#   power        = external meter at the DC input, read manually: not measured here

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
MODE="${MODE:-image}"
LABEL="${LABEL:-$MODE}"
BUILD_DIR="${BUILD_DIR:-$ROOT/third_party/llama.cpp/build-cuda}"
MODEL="${MODEL:-$ROOT/models/Ministral-3-3B-Instruct-2512-Q4_K_M.gguf}"
MMPROJ="${MMPROJ:-$ROOT/models/mmproj-Ministral-3-3B-Instruct-2512-Q8_0.gguf}"
IMAGE="${IMAGE:-$ROOT/bench/images/test-720p.jpg}"
PROMPT_TEXT="${PROMPT_TEXT:-[INST]Explain in a few sentences how a heatsink keeps an electronic board cool.[/INST]}"
PROMPT_IMAGE="${PROMPT_IMAGE:-Describe the scene in two sentences. List the main objects you can see.}"
RUNS="${RUNS:-5}"
N_PREDICT="${N_PREDICT:-64}"
CTX="${CTX:-4096}"
THREADS="${THREADS:-4}"
NGL="${NGL:-99}"
IMAGE_MAX_TOKENS="${IMAGE_MAX_TOKENS:-256}"
EXTRA_ARGS="${EXTRA_ARGS:-}"
REQUIRE_MAX_CLOCKS="${REQUIRE_MAX_CLOCKS:-1}"

OUT="$ROOT/bench/runs/$(date +%Y%m%d-%H%M%S)-$LABEL"
mkdir -p "$OUT"

# ---- environment record -------------------------------------------------------
gpu_devfreq="$(ls -d /sys/devices/gpu.0/devfreq/* 2>/dev/null | head -1 || true)"
{
    echo "date: $(date '+%F %T')"
    echo "label: $LABEL  mode: $MODE  runs: $RUNS (+1 warm-up)"
    echo "model: $MODEL"
    [ "$MODE" = image ] && echo "mmproj: $MMPROJ" && echo "image: $IMAGE sha256=$(sha256sum "$IMAGE" | cut -d' ' -f1)"
    echo "params: n_predict=$N_PREDICT (ignore-eos) ctx=$CTX threads=$THREADS ngl=$NGL image_max_tokens=$IMAGE_MAX_TOKENS extra='$EXTRA_ARGS'"
    echo "env: $(env | grep -E '^(GGML|LLAMA|CUDA)_' | sort | tr '\n' ' ')"
    echo "llama.cpp: $(git -C "$(dirname "$(dirname "$BUILD_DIR")")/llama.cpp" rev-parse --short HEAD 2>/dev/null || echo unknown) build=$BUILD_DIR"
    echo "nvpmodel: $(nvpmodel -q 2>/dev/null | grep -m1 'NV Power Mode' || echo unknown)"
    echo "desktop (gdm3): $(systemctl is-active gdm3 2>/dev/null || true); x11 sessions: $(loginctl list-sessions --no-legend 2>/dev/null | awk '{print $1}' | xargs -r -n1 loginctl show-session -p Type --value 2>/dev/null | grep -c x11 || true)"
    if [ -n "$gpu_devfreq" ]; then
        echo "gpu freq: cur=$(cat "$gpu_devfreq/cur_freq") min=$(cat "$gpu_devfreq/min_freq") max=$(cat "$gpu_devfreq/max_freq") available_max=$(tr ' ' '\n' < "$gpu_devfreq/available_frequencies" | sort -n | tail -1)"
    fi
    echo "--- jetson_clocks --show"
    sudo -n /usr/bin/jetson_clocks --show 2>&1 || echo "(jetson_clocks --show unavailable without password)"
} > "$OUT/env.txt"

if [ "$REQUIRE_MAX_CLOCKS" = 1 ] && [ -n "$gpu_devfreq" ]; then
    gmin="$(cat "$gpu_devfreq/min_freq")"
    gtop="$(tr ' ' '\n' < "$gpu_devfreq/available_frequencies" | sort -n | tail -1)"
    if [ "$gmin" != "$gtop" ]; then
        echo "error: GPU min_freq ($gmin) is not pinned at max ($gtop): run 'sudo jetson_clocks' first, or set REQUIRE_MAX_CLOCKS=0" >&2
        exit 1
    fi
fi

# ---- one run --------------------------------------------------------------------
cooling_paths=()
for c in /sys/class/thermal/cooling_device*; do
    case "$(cat "$c/type" 2>/dev/null)" in cpu-balanced|gpu-balanced) cooling_paths+=("$c/cur_state");; esac
done

run_once() {
    local tag="$1" log="$OUT/$1"
    tegrastats --interval 500 --logfile "$log.tegrastats" & local tp=$!
    ( while :; do
          s=""; for p in "${cooling_paths[@]}"; do s="$s $(cat "$p")"; done
          echo "$s"; sleep 1
      done ) > "$log.cooling" & local cp=$!
    sleep 1   # tegrastats takes its first samples before the program starts
    local rc=0
    # ttft_wall.py writes $log.out / $log.err and prints ttft_wall_ms=<value>
    if [ "$MODE" = image ]; then
        # shellcheck disable=SC2086
        python3 "$ROOT/scripts/ttft_wall.py" "experimental CLI" "$log" -- \
            "$BUILD_DIR/bin/llama-mtmd-cli" -m "$MODEL" --mmproj "$MMPROJ" --image "$IMAGE" -p "$PROMPT_IMAGE" \
            -ngl "$NGL" -t "$THREADS" -c "$CTX" -n "$N_PREDICT" --ignore-eos --temp 0 -s 42 \
            --image-max-tokens "$IMAGE_MAX_TOKENS" --perf -lv 4 $EXTRA_ARGS \
            > "$log.ttft" || rc=$?
    else
        # shellcheck disable=SC2086
        python3 "$ROOT/scripts/ttft_wall.py" "generate: n_ctx" "$log" -- \
            "$BUILD_DIR/bin/llama-completion" -m "$MODEL" -p "$PROMPT_TEXT" -no-cnv --no-display-prompt \
            -ngl "$NGL" -t "$THREADS" -c "$CTX" -n "$N_PREDICT" --ignore-eos --temp 0 -s 42 \
            $EXTRA_ARGS > "$log.ttft" || rc=$?
    fi
    sleep 0.5
    kill "$tp" "$cp" 2>/dev/null || true
    wait "$tp" "$cp" 2>/dev/null || true
    if [ "$rc" != 0 ]; then
        echo "error: run $tag failed (rc=$rc), see $log.err" >&2
        exit 1
    fi
}

echo "config $LABEL: warm-up + $RUNS runs -> $OUT"
run_once warmup
for i in $(seq 1 "$RUNS"); do
    echo "  run $i/$RUNS"
    run_once "run$i"
done

# ---- parse and summarize ----------------------------------------------------------
python3 - "$OUT" "$RUNS" "$MODE" <<'PY'
import re, sys, statistics, os
out, runs, mode = sys.argv[1], int(sys.argv[2]), sys.argv[3]

def grab(pat, text, cast=float, default=None):
    ms = re.findall(pat, text)
    return cast(ms[0]) if ms else default

rows = []
for i in range(1, runs + 1):
    base = os.path.join(out, "run%d" % i)
    err = open(base + ".err", errors="replace").read()
    r = {"run": i}
    r["load_ms"]     = grab(r"load time =\s+([\d.]+) ms", err)
    r["prompt_ms"]   = grab(r"prompt eval time =\s+([\d.]+) ms", err)
    r["prompt_tok"]  = grab(r"prompt eval time =\s+[\d.]+ ms /\s+(\d+) tokens", err, int)
    r["eval_ms"]     = grab(r"\beval time =\s+([\d.]+) ms /\s+\d+ runs", err)
    r["eval_runs"]   = grab(r"\beval time =\s+[\d.]+ ms /\s+(\d+) runs", err, int)
    r["encode_ms"]   = grab(r"mtmd batch encoding done in (\d+) ms", err, float, 0.0)
    r["image_tok"]   = grab(r"n_tokens_batch = (\d+)", err, int, 0)
    if None in (r["prompt_ms"], r["prompt_tok"], r["eval_ms"], r["eval_runs"]):
        sys.exit("error: could not parse perf lines in %s.err" % base)
    # In image mode the vision encode runs inside libllama's prompt-eval window.
    r["prefill_ms"]  = r["prompt_ms"] - r["encode_ms"] if mode == "image" else r["prompt_ms"]
    r["prefill_tps"] = r["prompt_tok"] / (r["prefill_ms"] / 1000.0)
    r["decode_tps"]  = r["eval_runs"] / (r["eval_ms"] / 1000.0)
    r["ttft_ms"]     = grab(r"ttft_wall_ms=([\d.]+)", open(base + ".ttft").read())
    if r["ttft_ms"] is None:
        sys.exit("error: no wall-clock TTFT in %s.ttft" % base)
    ts = open(base + ".tegrastats").read().splitlines()
    ram = [int(x) for l in ts for x in re.findall(r"RAM (\d+)/", l)]
    gpu_t = [float(x) for l in ts for x in re.findall(r"GPU@([\d.]+)C", l)]
    cpu_t = [float(x) for l in ts for x in re.findall(r"MCPU@([\d.]+)C", l)]
    r["ram_peak_mb"]  = max(ram)
    r["ram_delta_mb"] = max(ram) - ram[0]   # first sample: taken before the program starts
    r["gpu_temp_max"] = max(gpu_t) if gpu_t else float("nan")
    r["cpu_temp_max"] = max(cpu_t) if cpu_t else float("nan")
    cool = [int(x) for l in open(base + ".cooling") for x in l.split()]
    r["throttle_max_state"] = max(cool) if cool else 0
    rows.append(r)

cols = ["run", "ttft_ms", "encode_ms", "image_tok", "prompt_tok", "prompt_ms", "prefill_ms", "prefill_tps",
        "eval_runs", "eval_ms", "decode_tps", "load_ms", "ram_peak_mb", "ram_delta_mb",
        "gpu_temp_max", "cpu_temp_max", "throttle_max_state"]
with open(os.path.join(out, "runs.csv"), "w") as f:
    f.write(",".join(cols) + "\n")
    for r in rows:
        f.write(",".join(("%.2f" % r[c]) if isinstance(r[c], float) else str(r[c]) for c in cols) + "\n")

med = {c: statistics.median([r[c] for r in rows]) for c in cols if c != "run"}
lines = [
    "median of %d runs (%s):" % (runs, mode),
    "  TTFT (wall)    %8.0f ms" % med["ttft_ms"],
    "  image encode   %8.0f ms  (%d image tokens)" % (med["encode_ms"], med["image_tok"]),
    "  prefill        %8.2f t/s (%d prompt tokens, %.0f ms)" % (med["prefill_tps"], med["prompt_tok"], med["prefill_ms"]),
    "  decode         %8.2f t/s (%d tokens)" % (med["decode_tps"], med["eval_runs"]),
    "  model load     %8.0f ms  (not in TTFT)" % med["load_ms"],
    "  RAM peak       %8.0f MB  (delta %+.0f MB vs before the run)" % (med["ram_peak_mb"], med["ram_delta_mb"]),
    "  temp max       GPU %.1f C, CPU %.1f C; throttle cooling state max %d" % (
        max(r["gpu_temp_max"] for r in rows), max(r["cpu_temp_max"] for r in rows), max(r["throttle_max_state"] for r in rows)),
    "  spread         TTFT %.0f-%.0f ms, decode %.2f-%.2f t/s (min-max over runs)" % (
        min(r["ttft_ms"] for r in rows), max(r["ttft_ms"] for r in rows),
        min(r["decode_tps"] for r in rows), max(r["decode_tps"] for r in rows)),
    "  power          external meter, read manually (not measured by this script)",
]
open(os.path.join(out, "summary.txt"), "w").write("\n".join(lines) + "\n")
print("\n".join(lines))
PY
echo "results: $OUT"
